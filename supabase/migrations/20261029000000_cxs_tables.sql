-- Fonctions de CalXsthenos intégrées à TB my Coach.
-- Toutes les tables et fonctions portent le préfixe cxs_ pour ne rien écraser
-- (TB my Coach a déjà messages, is_coach(), etc.). Aucune donnée de test n'est copiée.
-- Aucun déclencheur sur auth.users : les inscriptions TB my Coach ne sont pas touchées.

create table if not exists public.cxs_tiers (
  id text primary key,
  rank int not null,
  name text not null,
  msgs_per_week int
);
alter table public.cxs_tiers enable row level security;
insert into public.cxs_tiers (id, rank, name, msgs_per_week) values
  ('free', 0, 'Gratuit', 2),
  ('premium', 1, 'Premium', 5),
  ('essentiel', 2, 'Suivi essentiel', 10),
  ('suivi', 3, 'Suivi', 20),
  ('avance', 4, 'Suivi avancé', 50),
  ('surmesure', 5, 'Coaching sur mesure', null)
on conflict (id) do nothing;

create table if not exists public.cxs_profiles (
  id uuid primary key,
  email text,
  name text,
  onboarding jsonb default '{}'::jsonb,
  stats jsonb default '{}'::jsonb,
  tier text not null default 'free',
  tier_until date,
  is_coach boolean not null default false,
  created_at timestamptz not null default now(),
  last_seen timestamptz default now()
);

create table if not exists public.cxs_member_data (
  user_id uuid primary key,
  data jsonb not null default '{}'::jsonb,
  summary jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.cxs_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  sender uuid not null,
  body text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  reactions jsonb not null default '{}'::jsonb
);

create table if not exists public.cxs_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid,
  title text not null,
  body text,
  created_at timestamptz not null default now()
);

create table if not exists public.cxs_library (
  id bigint generated by default as identity primary key,
  kind text not null,
  name text not null,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cxs_coach_store (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.cxs_profiles enable row level security;
alter table public.cxs_member_data enable row level security;
alter table public.cxs_messages enable row level security;
alter table public.cxs_notifications enable row level security;
alter table public.cxs_library enable row level security;
alter table public.cxs_coach_store enable row level security;

create or replace function public.cxs_is_coach() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_coach from public.cxs_profiles where id = auth.uid()), false)
$$;

create or replace function public.cxs_msgs_left(uid uuid default auth.uid()) returns integer
language sql stable security definer set search_path = public as $$
  select case when t.msgs_per_week is null then null
    else greatest(0, t.msgs_per_week - (select count(*) from public.cxs_messages m
      where m.user_id = uid and m.sender = uid and m.created_at > now() - interval '7 days'))::int end
  from public.cxs_profiles p join public.cxs_tiers t on t.id = p.tier where p.id = uid
$$;

create or replace function public.cxs_set_tier(target uuid, new_tier text, until date default null) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.cxs_is_coach() then raise exception 'réservé au coach'; end if;
  update public.cxs_profiles set tier = new_tier, tier_until = until where id = target;
end $$;

create or replace function public.cxs_notify_member_on_reply() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.sender <> new.user_id then
    insert into public.cxs_notifications (user_id, title, body) values (new.user_id, 'Nouveau message de Thomas', left(new.body, 140));
  end if;
  return new;
end $$;

drop trigger if exists cxs_notify_on_reply on public.cxs_messages;
create trigger cxs_notify_on_reply after insert on public.cxs_messages
  for each row execute function public.cxs_notify_member_on_reply();

-- Règles d'accès (mêmes que CalXsthenos, avec les fonctions cxs_)
create policy "cxs lire son profil ou coach" on public.cxs_profiles for select to authenticated using (id = auth.uid() or public.cxs_is_coach());
create policy "cxs modifier son profil" on public.cxs_profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

create policy "cxs lire ses données ou coach" on public.cxs_member_data for select to authenticated using (user_id = auth.uid() or public.cxs_is_coach());
create policy "cxs membre écrit ses données" on public.cxs_member_data for insert to authenticated with check (user_id = auth.uid());
create policy "cxs membre met à jour ses données" on public.cxs_member_data for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "cxs membre supprime ses données" on public.cxs_member_data for delete to authenticated using (user_id = auth.uid());

create policy "cxs lire ses messages ou coach" on public.cxs_messages for select to authenticated using (user_id = auth.uid() or public.cxs_is_coach());
create policy "cxs marquer lu" on public.cxs_messages for update to authenticated using (user_id = auth.uid() or public.cxs_is_coach());
create policy "cxs membre écrit dans son fil (quota)" on public.cxs_messages for insert to authenticated
  with check (sender = auth.uid() and (public.cxs_is_coach() or (user_id = auth.uid() and coalesce(public.cxs_msgs_left(), 1) > 0)));

create policy "cxs lire ses notifications" on public.cxs_notifications for select to authenticated using (user_id is null or user_id = auth.uid() or public.cxs_is_coach());
create policy "cxs coach envoie des notifications" on public.cxs_notifications for insert to authenticated with check (public.cxs_is_coach());
create policy "cxs coach supprime des notifications" on public.cxs_notifications for delete to authenticated using (public.cxs_is_coach());

create policy "cxs bibliothèque lisible" on public.cxs_library for select to authenticated using (true);
create policy "cxs coach ajoute à la bibliothèque" on public.cxs_library for insert to authenticated with check (public.cxs_is_coach());
create policy "cxs coach modifie la bibliothèque" on public.cxs_library for update to authenticated using (public.cxs_is_coach()) with check (public.cxs_is_coach());
create policy "cxs coach retire de la bibliothèque" on public.cxs_library for delete to authenticated using (public.cxs_is_coach());

create policy "cxs coach lit son espace" on public.cxs_coach_store for select to authenticated using (public.cxs_is_coach());
create policy "cxs coach écrit son espace" on public.cxs_coach_store for insert to authenticated with check (public.cxs_is_coach());
create policy "cxs coach modifie son espace" on public.cxs_coach_store for update to authenticated using (public.cxs_is_coach()) with check (public.cxs_is_coach());
create policy "cxs coach supprime dans son espace" on public.cxs_coach_store for delete to authenticated using (public.cxs_is_coach());

create policy "cxs paliers lisibles" on public.cxs_tiers for select to anon, authenticated using (true);
